SET NAMES utf8mb4;
SET time_zone = '-07:00';

CREATE TABLE IF NOT EXISTS ajustes (
  clave VARCHAR(64) NOT NULL PRIMARY KEY,
  valor VARCHAR(500) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS clientes (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL,
  telefono VARCHAR(40) NOT NULL,
  correo VARCHAR(160) NOT NULL DEFAULT '',
  direccion VARCHAR(255) NOT NULL DEFAULT '',
  lat DECIMAL(9,6) NOT NULL DEFAULT 0,
  lng DECIMAL(9,6) NOT NULL DEFAULT 0,
  servicio VARCHAR(120) NOT NULL DEFAULT '',
  precio DECIMAL(10,2) NOT NULL DEFAULT 0,
  frecuencia VARCHAR(20) NOT NULL DEFAULT 'semanal',
  dia_servicio TINYINT NOT NULL DEFAULT 1,
  paridad TINYINT NOT NULL DEFAULT 0,
  notas VARCHAR(500) NOT NULL DEFAULT '',
  activo TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cuadrillas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  notas VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS empleados (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL,
  telefono VARCHAR(40) NOT NULL DEFAULT '',
  correo VARCHAR(160) NOT NULL DEFAULT '',
  direccion VARCHAR(255) NOT NULL DEFAULT '',
  puesto VARCHAR(40) NOT NULL DEFAULT 'Jardinero',
  notas VARCHAR(500) NOT NULL DEFAULT '',
  pago_hora DECIMAL(10,2) NOT NULL DEFAULT 20,
  codigo VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS empleado_cuadrillas (
  empleado_id INT NOT NULL,
  cuadrilla_id INT NOT NULL,
  orden TINYINT NOT NULL DEFAULT 1,
  PRIMARY KEY (empleado_id, cuadrilla_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS estimados (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  numero VARCHAR(20) NOT NULL UNIQUE,
  cliente_id INT NULL,
  nombre VARCHAR(160) NOT NULL,
  telefono VARCHAR(40) NOT NULL DEFAULT '',
  direccion VARCHAR(255) NOT NULL DEFAULT '',
  nota VARCHAR(500) NOT NULL DEFAULT '',
  nota_cliente VARCHAR(500) NOT NULL DEFAULT '',
  firma VARCHAR(255) NOT NULL DEFAULT '',
  firmo_nombre VARCHAR(160) NOT NULL DEFAULT '',
  firmado_en DATE NULL,
  creado DATE NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'enviado'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS estimado_partidas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estimado_id INT NOT NULL,
  descripcion VARCHAR(160) NOT NULL,
  cantidad DECIMAL(10,2) NOT NULL DEFAULT 1,
  precio DECIMAL(10,2) NOT NULL DEFAULT 0,
  orden INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoices (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  numero VARCHAR(20) NOT NULL UNIQUE,
  estado VARCHAR(20) NOT NULL DEFAULT 'por-cobrar',
  emitido DATE NOT NULL,
  pagado_en DATE NULL,
  pago VARCHAR(40) NOT NULL DEFAULT '',
  nombre VARCHAR(160) NOT NULL,
  telefono VARCHAR(40) NOT NULL DEFAULT '',
  direccion VARCHAR(255) NOT NULL DEFAULT '',
  subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
  impuesto DECIMAL(10,2) NOT NULL DEFAULT 0,
  total DECIMAL(10,2) NOT NULL DEFAULT 0,
  origen VARCHAR(20) NOT NULL DEFAULT 'estimado',
  estimado_id INT NULL,
  cliente_id INT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoice_partidas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  invoice_id INT NOT NULL,
  descripcion VARCHAR(160) NOT NULL,
  cantidad DECIMAL(10,2) NOT NULL DEFAULT 1,
  precio DECIMAL(10,2) NOT NULL DEFAULT 0,
  orden INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoice_costos (
  invoice_id INT NOT NULL PRIMARY KEY,
  materiales DECIMAL(10,2) NOT NULL DEFAULT 0,
  mano_obra DECIMAL(10,2) NOT NULL DEFAULT 0,
  basurero DECIMAL(10,2) NOT NULL DEFAULT 0,
  otros DECIMAL(10,2) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS visitas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  cliente_id INT NOT NULL,
  fecha DATE NOT NULL,
  foto_antes VARCHAR(255) NOT NULL DEFAULT '',
  foto_despues VARCHAR(255) NOT NULL DEFAULT '',
  empleado_id INT NULL,
  iniciada TINYINT(1) NOT NULL DEFAULT 0,
  terminada TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY uq_visita (cliente_id, fecha)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS fichajes (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  empleado_id INT NOT NULL,
  entrada DATETIME NOT NULL,
  salida DATETIME NULL,
  lat_entrada DECIMAL(9,6) NULL,
  lng_entrada DECIMAL(9,6) NULL,
  lat_salida DECIMAL(9,6) NULL,
  lng_salida DECIMAL(9,6) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gastos (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  fecha DATE NOT NULL,
  categoria VARCHAR(40) NOT NULL,
  descripcion VARCHAR(255) NOT NULL DEFAULT '',
  monto DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ruta_dia (
  fecha DATE NOT NULL PRIMARY KEY,
  cuadrilla_id INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sesiones (
  token CHAR(64) NOT NULL PRIMARY KEY,
  expira DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
