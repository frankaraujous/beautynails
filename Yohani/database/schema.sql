SET NAMES utf8mb4;
SET time_zone = '-07:00';

CREATE TABLE IF NOT EXISTS ajustes (
  clave VARCHAR(64) NOT NULL PRIMARY KEY,
  valor VARCHAR(500) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS servicios (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  precio DECIMAL(10,2) NOT NULL DEFAULT 0,
  orden INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS disponibilidad (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  fecha DATE NOT NULL,
  hora TIME NOT NULL,
  UNIQUE KEY uq_hora (fecha, hora)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dias_libres (
  fecha DATE NOT NULL PRIMARY KEY
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS citas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  telefono VARCHAR(40) NOT NULL,
  correo VARCHAR(160) NOT NULL DEFAULT '',
  servicio VARCHAR(80) NOT NULL,
  pago VARCHAR(40) NOT NULL,
  color VARCHAR(16) NOT NULL DEFAULT '',
  codigo_transferencia VARCHAR(20) NOT NULL DEFAULT '',
  fecha DATE NOT NULL,
  hora TIME NOT NULL,
  foto1 VARCHAR(255) NOT NULL DEFAULT '',
  foto2 VARCHAR(255) NOT NULL DEFAULT '',
  alergia VARCHAR(500) NOT NULL DEFAULT '',
  creada_en DATETIME NOT NULL,
  confirmada TINYINT(1) NOT NULL DEFAULT 0,
  cancelada TINYINT(1) NOT NULL DEFAULT 0,
  terminada TINYINT(1) NOT NULL DEFAULT 0,
  monto DECIMAL(10,2) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gastos (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  monto DECIMAL(10,2) NOT NULL,
  fecha DATE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sesiones (
  token CHAR(64) NOT NULL PRIMARY KEY,
  expira DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
